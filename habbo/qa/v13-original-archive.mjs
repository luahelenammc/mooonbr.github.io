import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'qa/v13-artifacts');fs.mkdirSync(out,{recursive:true});
const original=JSON.parse(fs.readFileSync(path.join(root,'v13/source-manifest.json')));
const ledger=JSON.parse(fs.readFileSync(path.join(root,'v13/native-ledger.json')));
let count=0;
const ok=(pass,msg)=>{assert.ok(pass,msg);count++;};
ok(original.newRares.length===79,'79 sourced rare and HC additions required');
ok(original.animations.length===2,'2 hologram animations required');
ok(ledger.assets.length===81,'81 original native sprites required');
for(const a of ledger.assets)ok(a.sha256.length===64&&a.width>=20&&a.height>=20,'native asset verified '+a.id);
ok(ledger.assets.find(x=>x.id==='holopod').frames===14,'Holoboy must contain 14 original frames');
ok(ledger.assets.find(x=>x.id==='hologirl').frames===16,'Hologirl must contain 16 original frames');
const browser=await chromium.launch({headless:true});
try{
 for(const [lang,route] of [['root',''],['pt','pt-br/'],['en','en/']]){
  for(const [device,viewport] of [['desktop',{width:1440,height:900}],['mobile',{width:390,height:844}]]){
   const context=await browser.newContext({viewport,reducedMotion:'no-preference'});
   const page=await context.newPage(),errors=[],failed=[];
   page.on('pageerror',e=>errors.push(e.message));
   page.on('requestfailed',r=>failed.push(r.url()));
   await page.goto('http://127.0.0.1:4173/habbo/'+route,{waitUntil:'networkidle'});
   ok(await page.locator('.cinematic-dock').count()===1,'Places Dock must be preserved');
   ok(await page.locator('html.v12-quiet-ready').count()===1,'progressive enhancement works');
   ok(await page.locator('link[href*="v13-home.css?v=20261019-v15.1"]').count()===1,'v13 stylesheet missing');
   ok(await page.locator('script[src*="v13-home.js?v=20261019-v16.1"]').count()===1,'v13 script missing');
   ok(await page.locator('#raros [data-v9-item]').count()===148,'148 historic rare and HC specimens required');
   ok(await page.locator('#emblemas [data-v9-item]').count()===101,'101 global classic badges missing');
   ok(await page.locator('#raros .v11-family-grid a').count()===15,'15 groups expected');
   ok(await page.locator('#raros .v11-family-grid a:visible').count()===15,'all 15 groups must be visible');
   ok(await page.locator('#emblemas .v11-family-grid a:visible').count()===7,'all 7 badge families visible');
   ok(await page.locator('#raros-family-smoke-machines [data-v9-item]').count()===10,'ten smoke machines');
   ok(await page.locator('#raros-family-monoliths [data-v9-item]').count()===10,'ten monoliths');
   ok(await page.locator('#raros-family-collectables-2008-2009 [data-v9-item]').count()===16,'sixteen historical collectibles');
   ok(await page.locator('#raros-family-v12-rare-avulsos [data-v9-item]').count()===14,'existing 14 rare singles intact');
   ok(await page.locator('#raros .v11-family-grid').evaluate(e=>getComputedStyle(e).overflowX==='visible'&&e.scrollWidth<=e.clientWidth+2),'family directory cannot hide horizontal overflow');
   ok(await page.locator('[href*="badge-br"]').count()===0,'regional-only badges must be excluded');
   ok(await page.locator('#raros [data-v9-id="holopod"] img').first().getAttribute('src')==='/habbo/assets/v13/native/holo_boy_anim.gif','Holoboy animated src');
   ok(await page.locator('#raros [data-v9-id="hologirl"] img').first().getAttribute('src')==='/habbo/assets/v13/native/holo_girl_anim.gif','Hologirl animated src');
   const holo=page.locator('#raros [data-v9-id="holopod"] img').first();
   await page.locator('#raros .v11-family-grid a[href$="holograms"]').click();
   await holo.scrollIntoViewIfNeeded();
   await page.waitForFunction(()=>{const img=document.querySelector('#raros [data-v9-id="holopod"] img');return img?.complete&&img.naturalWidth===40&&img.naturalHeight===71;});
   ok(await holo.evaluate(x=>x.naturalWidth===40&&x.naturalHeight===71),'Holoboy native GIF loads');
   await page.locator('#raros [data-v9-id="holopod"]').click();
   ok(await page.locator('.v9-home-dialog[open]').count()===1,'hologram dialog opens');
   ok((await page.locator('[data-v9-dialog-image]').getAttribute('src'))?.includes('holo_boy_anim.gif'),'dialog uses moving hologram');
   await page.keyboard.press('Escape');
   await page.locator('#raros .v11-family-grid a[href$="smoke-machines"]').click();
   const smoke=page.locator('#raros-family-smoke-machines .v9-home-item').first();
   await smoke.click();
   ok((await page.locator('[data-v9-dialog-link]').getAttribute('href'))?.includes('/v13-smoke-'),'smoke historical records linked');
   ok((await page.locator('[data-v9-dialog-counter]').textContent())?.trim()==='1 / 10','lightbox scoped to 10 smoke machines');
   await page.keyboard.press('Escape');
   await page.locator('#raros .v11-family-grid a[href$="collectables-2008-2009"]').click();
   ok(await page.locator('#raros-family-collectables-2008-2009:visible').count()===1,'collectables navigable');
   await page.locator('#raros-family-collectables-2008-2009 [data-v9-item]').first().click();
   ok((await page.locator('[data-v9-dialog-counter]').textContent())?.trim()==='1 / 16','collectibles lightbox scoped');
   await page.keyboard.press('Escape');
   ok(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+2),'viewport overflow');
   ok(errors.length===0,'JS errors: '+errors);
   ok(failed.length===0,'failed requests: '+failed);
   await page.locator('#raros .v11-family-directory').scrollIntoViewIfNeeded();
   await page.screenshot({path:path.join(out,lang+'-'+device+'-family-atlas.png')});
   await context.close();
  }
  const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const page=await context.newPage();
  await page.goto('http://127.0.0.1:4173/habbo/'+route,{waitUntil:'networkidle'});
  await page.locator('#raros .v11-family-grid a[href$="holograms"]').click();
  const img=page.locator('#raros [data-v9-id="hologirl"] img').first();
  await img.scrollIntoViewIfNeeded();
  ok((await img.evaluate(x=>x.currentSrc)).includes('/v5/rares/hologirl.gif'),'reduced-motion static hologirl via picture media');
  await page.locator('#raros [data-v9-id="hologirl"]').click();
  ok((await page.locator('[data-v9-dialog-image]').getAttribute('src')).includes('/v5/rares/hologirl.gif'),'lightbox must respect reduced motion');
  await context.close();
  const c=await browser.newContext({viewport:{width:1200,height:800}});
  const p=await c.newPage();
  await p.goto('http://127.0.0.1:4173/habbo/'+(lang==='en'?'en/rares/':'pt-br/raros/'),{waitUntil:'networkidle'});
  ok(await p.locator('.v8-specimen').count()===148,'standalone rare archive complete');
  ok(await p.locator('.v8-family').count()===15,'standalone 15 families');
  await p.goto('http://127.0.0.1:4173/habbo/'+(lang==='en'?'en/rare/':'pt-br/raro/')+'v13-collectible-gondola/',{waitUntil:'networkidle'});
  ok(await p.locator('main.v13-detail-main img').count()===1,'individual V13 collection detail exists');
  ok(await p.locator('main.v13-detail-main a[href*="habboxwiki.com"]').count()===1,'original source link retained');
  await p.goto('http://127.0.0.1:4173/habbo/'+(lang==='en'?'en/rare/':'pt-br/raro/')+'holopod/',{waitUntil:'networkidle'});
  ok(await p.locator('article.detail picture img[src$="/holo_boy_anim.gif"]').count()===1,'historic Holoboy record upgraded to authentic GIF');
  ok(await p.locator('article.detail picture source[media="(prefers-reduced-motion: reduce)"]').count()===1,'historic Holoboy reduced-motion still source preserved');
  await c.close();
 }
 const nojs=await browser.newContext({viewport:{width:390,height:844},javaScriptEnabled:false});
 const page=await nojs.newPage();
 await page.goto('http://127.0.0.1:4173/habbo/pt-br/',{waitUntil:'load'});
 ok(await page.locator('#raros .v11-family-grid a:visible').count()===15,'no JS retains all 15 archival families');
 ok(await page.locator('#raros .v9-family:visible').count()===15,'no JS retains 15 archive galleries');
 await nojs.close();
}finally{await browser.close();}
fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({status:'passed',checks:count,rares:148,badges:101,newRares:79,animations:2,originals:81},null,2));
console.log('V13 ORIGINAL RARES PASS '+count);
