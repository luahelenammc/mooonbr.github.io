import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'qa/v14-artifacts');
fs.mkdirSync(out,{recursive:true});
const source=JSON.parse(fs.readFileSync(path.join(root,'v13/source-manifest.json'),'utf8'));
const ledger=JSON.parse(fs.readFileSync(path.join(root,'v13/native-ledger.json'),'utf8'));
let checks=0;
const verify=(v,m)=>{assert.ok(v,m);checks++};
const base='http://127.0.0.1:4173/habbo/';
verify(source.newRares.length===79,'79 additions must be present');
verify(ledger.assets.length===81,'81 original archived sprites must be present');
const monoliths=source.newRares.filter(x=>x.family==='monoliths');
const lasers=source.newRares.filter(x=>x.family==='laser-gates');
verify(monoliths.length===10,'ten monolith records');
verify(lasers.length===10,'ten distinct laser gate records');
verify(monoliths.every(x=>x.pt.startsWith('Monolito ')&&x.familyPt==='Monolitos'&&x.familyEn==='Monoliths'),'editorial display terms for mono_*');
verify(monoliths.every(x=>x.historicNameEn&&x.source.includes('v7_mono.html')),'documented names and source retained');
verify(lasers.every(x=>x.source.includes('v7_laser.html')&&x.url.includes('/laser_')&&x.familyPt==='Portas laser'),'separate original laser family');
verify(new Set(lasers.map(x=>x.url)).size===10,'every laser asset has its own source file');
verify(new Set(lasers.map(x=>x.local)).size===10,'no one sprite recycled for multiple laser objects');
const laserDigests=lasers.map(x=>ledger.assets.find(a=>a.id===x.id));
verify(laserDigests.every(x=>x?.type==='gif'&&x.width===56&&x.height===71&&x.bytes>200),'full room-scale laser sprite originals');
verify(new Set(laserDigests.map(x=>x.sha256)).size===10,'all ten laser render hashes must be unique');
const browser=await chromium.launch({headless:true});
try{
 for(const [locale,route] of [['root',''],['pt','pt-br/'],['en','en/']]){
  const en=locale==='en';
  for(const [device,viewport] of [['desktop',{width:1440,height:900}],['mobile',{width:390,height:844}],['small',{width:320,height:720}]]){
   const context=await browser.newContext({viewport,reducedMotion:'no-preference'});
   const page=await context.newPage(),errors=[],failed=[];
   page.on('pageerror',e=>errors.push(e.message));
   page.on('requestfailed',req=>failed.push(req.url()));
   await page.goto(base+route,{waitUntil:'networkidle'});
   const nav=page.locator('.collection-switch a').first();
   verify((await nav.textContent()).trim()===(en?'Public Spaces':'Espaços Públicos'),'main chapter label '+locale+'/'+device);
   verify(await nav.getAttribute('href')!==null,'navigation still resolves to chapter');
   verify(await page.locator('#lugares.cinematic-dock').count()===1,'stable Places Dock anchor preserved');
   verify(await page.locator('#raros [data-v9-item]').count()===158,'all 148 archive specimens preserved');
   verify(await page.locator('#emblemas [data-v9-item]').count()===101,'101 global badges preserved');
   verify(await page.locator('#raros .v11-family-grid a').count()===15,'all 15 archive families present');
   verify(await page.locator('#raros .v11-family-grid a:visible').count()===15,'none of the 15 categories hidden');
   verify(await page.locator('#emblemas .v11-family-grid a:visible').count()===7,'global badge families intact');
   verify(await page.locator('#raros-family-monoliths [data-v9-item]').count()===10,'monolith gallery 10');
   verify(await page.locator('#raros-family-laser-gates [data-v9-item]').count()===10,'laser portals gallery 10');
   verify(await page.locator('#raros-family-smoke-machines [data-v9-item]').count()===10,'smoke machine gallery intact');
   verify(await page.locator('#raros-family-collectables-2008-2009 [data-v9-item]').count()===16,'collectibles gallery intact');
   verify(await page.locator('#raros-family-v12-rare-avulsos [data-v9-item]').count()===15,'14 classic singles preserved');
   verify(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+2),'whole viewport must not scroll sideways');
   verify(await page.locator('.collection-switch').evaluate(x=>x.scrollWidth<=x.clientWidth+2),'new longer chapter label must fit viewport');
   const first=page.locator('#raros .v11-family-grid a[href$="laser-gates"]');
   await first.click();
   verify(await page.locator('#raros-family-laser-gates:visible').count()===1,'new family directly navigable');
   const img=page.locator('#raros-family-laser-gates .v9-home-item img').first();
   await img.scrollIntoViewIfNeeded();
   await page.waitForFunction(()=>{let x=document.querySelector('#raros-family-laser-gates .v9-home-item img');return x?.complete&&x.naturalWidth===56&&x.naturalHeight===71;});
   verify(await img.evaluate(x=>x.naturalWidth===56&&x.naturalHeight===71),'full original portal render loads, not inventory icon');
   await page.locator('#raros-family-laser-gates [data-v9-item]').first().click();
   verify(await page.locator('.v9-home-dialog[open]').count()===1,'new lightbox works');
   verify((await page.locator('[data-v9-dialog-counter]').textContent()).trim()==='1 / 10','laser lightbox confined to family');
   verify((await page.locator('[data-v9-dialog-link]').getAttribute('href')).includes('v14-laser-'),'laser has distinct historical record');
   await page.keyboard.press('Escape');
   await page.locator('#raros .v11-family-grid a[href$="monoliths"]').click();
   verify(await page.locator('#raros-family-monoliths [data-v9-title]').count()===10,'monolith metadata preserved');
   const mono=page.locator('#raros-family-monoliths [data-v9-item]').first();
   verify((await mono.getAttribute('data-v9-title')).startsWith(en?'Pink Monolith':'Monolito rosa'),'monolith names shown correctly');
   verify(await page.locator('#raros-family-laser-gates [data-v9-item]').count()===10,'laser family remains separate after monolith navigation');
   verify(errors.length===0,'no client JS errors: '+errors.join('; '));
   verify(failed.length===0,'no missing sprite requests: '+failed.join('; '));
   await page.locator('#raros .v11-family-directory').scrollIntoViewIfNeeded();
   await page.screenshot({path:path.join(out,locale+'-'+device+'-family-atlas.png')});
   await context.close();
  }
  const ctx=await browser.newContext({viewport:{width:1200,height:800}});
  const p=await ctx.newPage();
  await p.goto(base+(en?'en/rares/':'pt-br/raros/'),{waitUntil:'networkidle'});
  verify(await p.locator('.v8-family').count()===15,'15 families in stand-alone archive');
  verify(await p.locator('.v8-specimen').count()===158,'148 sprites in stand-alone archive');
  verify((await p.locator('.v8-top-links a').first().textContent()).trim()===(en?'Public Spaces':'Espaços Públicos'),'archive nav has corrected label');
  await p.goto(base+(en?'en/rare/':'pt-br/raro/')+'v13-monolith-pink/',{waitUntil:'networkidle'});
  verify(await p.locator('main.v13-detail-main h1').textContent().then(s=>s.startsWith(en?'Pink Monolith':'Monolito rosa')),'monolith record title corrected');
  verify(await p.locator('main .v13-historic-alias').textContent().then(s=>s.includes('Pink Spaceship Door')),'historic alternate catalogue nomenclature retained');
  verify((await p.locator('.v8-top-links a').first().textContent()).trim()===(en?'Public Spaces':'Espaços Públicos'),'monolith record nav translated');
  await p.goto(base+(en?'en/rare/':'pt-br/raro/')+'v14-laser-red/',{waitUntil:'networkidle'});
  verify(await p.locator('main.v13-detail-main img[src$="v14-laser-red.gif"]').count()===1,'new source-backed laser details exist');
  verify(await p.locator('main.v13-detail-main a[href*="v7_laser.html"]').count()===1,'original archive link preserved');
  await p.goto(base+(en?'en/rare/':'pt-br/raro/')+'holopod/',{waitUntil:'networkidle'});
  verify((await p.locator('nav a').first().textContent()).trim()===(en?'Public Spaces':'Espaços Públicos'),'inherited classic rare record nav corrected');
  await ctx.close();
 }
 const ctx=await browser.newContext({viewport:{width:390,height:844},javaScriptEnabled:false});
 const p=await ctx.newPage();
 await p.goto(base+'pt-br/',{waitUntil:'load'});
 verify(await p.locator('#raros .v11-family-grid a:visible').count()===15,'no JS retains the full archive family index');
 verify(await p.locator('#raros .v9-family:visible').count()===15,'no JS keeps all archival galleries readable');
 await ctx.close();
}finally{await browser.close();}
fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({status:'passed',checks,rares:148,monoliths:10,laserGates:10,classicHC:33,badges:101,archivedNativeSprites:81},null,2));
console.log('V14 LASER + MONOLITH + PUBLIC SPACES PASS',checks);
